export function normalizeAgentPlatforms(input) {
    const seen = new Set();
    return (Array.isArray(input) ? input : DEFAULT_AGENT_PLATFORMS).map((item, index) => ({
        id: Number(item?.id) || null,
        code: String(item?.code || item?.id || '').trim(),
        name: String(item?.name || '').trim(),
        softwareUnique: String(item?.softwareUnique || '').trim(),
        theme: normalizeAgentPlatformTheme(item?.theme),
        builtin: Boolean(item?.builtin),
        sortOrder: Number(item?.sortOrder) || 1000 + index * 10,
        taskCount: Number(item?.taskCount) || 0,
        catalogTaskCount: Number(item?.catalogTaskCount) || 0,
        catalogSyncStatus: String(item?.catalogSyncStatus || 'never'),
        catalogSyncedAt: item?.catalogSyncedAt || null
    })).filter(item => {
        const key = normalizePlatformKey(item.softwareUnique);
        if (!item.code || !item.name || !key || seen.has(key)) return false;
        seen.add(key);
        return true;
    }).sort((left, right) => Number(right.builtin) - Number(left.builtin)
        || left.sortOrder - right.sortOrder || left.code.localeCompare(right.code, 'zh-CN'));
}

