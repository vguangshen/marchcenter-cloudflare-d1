const LEGACY_CUSTOM_KEY = 'marchcenter:paas-v2:custom-platforms';
const LEGACY_OVERRIDES_KEY = 'marchcenter:paas-v2:builtin-overrides';

export function readLegacyAgentPlatforms() {
    const platforms = new Map(DEFAULT_AGENT_PLATFORMS.map(item => [item.softwareUnique, { ...item }]));
    let foundLegacy = false;
    try {
        const overrides = JSON.parse(localStorage.getItem(LEGACY_OVERRIDES_KEY) || '{}');
        if (overrides && typeof overrides === 'object' && !Array.isArray(overrides)) {
            for (const [key, override] of Object.entries(overrides)) {
                const builtin = platforms.get(key);
                if (!builtin || !override || typeof override !== 'object') continue;
                platforms.set(key, { ...builtin, code: String(override.code || builtin.code).trim(), name: String(override.name || builtin.name).trim() });
                foundLegacy = true;
            }
        }
    } catch { /* Keep cloud state independent from invalid legacy storage. */ }
    try {
        const custom = JSON.parse(localStorage.getItem(LEGACY_CUSTOM_KEY) || '[]');
        if (Array.isArray(custom)) for (const item of custom) {
            const softwareUnique = String(item?.softwareUnique || '').trim();
            const code = String(item?.code || '').trim();
            const name = String(item?.name || '').trim();
            if (!softwareUnique || !code || !name) continue;
            platforms.set(softwareUnique, { softwareUnique, code, name, builtin: false });
            foundLegacy = true;
        }
    } catch { /* Malformed legacy data must not block loading the cloud list. */ }
    return foundLegacy ? [...platforms.values()] : [];
}

export function clearLegacyAgentPlatforms() {
    try {
        localStorage.removeItem(LEGACY_CUSTOM_KEY);
        localStorage.removeItem(LEGACY_OVERRIDES_KEY);
    } catch { /* Browsers may disable storage; cloud data is already saved. */ }
}
